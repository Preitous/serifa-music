def tr(key, language=DEFAULT_LANGUAGE):
    language_table = TRANSLATIONS.get(
        language,
        TRANSLATIONS[DEFAULT_LANGUAGE]
    )

    return language_table.get(
        key,
        TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    )
LANGUAGE_SETTINGS_KEY = "interface_language"


def load_language(settings):
    language = settings.value(
        LANGUAGE_SETTINGS_KEY,
        DEFAULT_LANGUAGE,
        type=str
    )

    if language not in SUPPORTED_LANGUAGES:
        return DEFAULT_LANGUAGE

    return language


def save_language(settings, language):
    if language not in SUPPORTED_LANGUAGES:
        raise ValueError("Idioma selecionado não é válido.")

    settings.setValue(LANGUAGE_SETTINGS_KEY, language)
    settings.sync()

    if settings.status() != settings.Status.NoError:
        raise RuntimeError("Não foi possível salvar a preferência de idioma.")
